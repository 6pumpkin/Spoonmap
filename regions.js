function searchKoreaSmallLocations(query) {
    if (!query || query.trim().length === 0) return [];
    const q = query.trim().toLowerCase();
    const results = [];
    for (const [large, smalls] of Object.entries(KOREA_REGIONS)) {
        for (const small of smalls) {
            if (small.toLowerCase().includes(q)) {
                results.push({
                    large: large,
                    small: small,
                    display: `[${large}] ${small}`
                });
            }
        }
    }
    return results;
}

